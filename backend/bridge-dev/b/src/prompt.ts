function seedText(brief: SeedBrief): string {
  return brief.seeds
    .map((s, i) => `- 후보 ${i + 1}: ${s.word}\n  흐름: ${s.arc}\n  (발단-앵커 유사도 ${s.sim}, 결말-앵커 연결 ${s.link}, 흥미 ${s.info})`)
    .join("\n");
}

